def set_run_default(run, size: float = 11, bold: bool = False, italic: bool = False, font: str = "Times New Roman"):
    run.font.name = font
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    r = run._element
    rpr = r.get_or_add_rPr()
    rFonts = rpr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rpr.insert(0, rFonts)
    rFonts.set(qn("w:ascii"), font)
    rFonts.set(qn("w:hAnsi"), font)
    rFonts.set(qn("w:cs"), font)


def add_heading_styled(doc, text: str, level: int = 1):
    if level == 0:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(text)
        set_run_default(run, size=16, bold=True)
        return p
    sizes = {1: 14, 2: 12, 3: 11, 4: 11}
    p = doc.add_paragraph()
    run = p.add_run(text)
    set_run_default(run, size=sizes.get(level, 11), bold=True)
    p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after = Pt(4)
    return p


def add_paragraph_text(doc, text: str, *, italic: bool = False, alignment=None):
    """Add a paragraph with mixed bold/italic via simple markdown parsing."""
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(4)
    p.paragraph_format.line_spacing = 1.2
    if alignment:
        p.alignment = alignment
    parts = re.split(r"(\*\*[^*]+\*\*|\*[^*]+\*)", text)
    for part in parts:
        if not part:
            continue
        if part.startswith("**") and part.endswith("**"):
            r = p.add_run(part[2:-2])
            set_run_default(r, bold=True, italic=italic)
        elif part.startswith("*") and part.endswith("*"):
            r = p.add_run(part[1:-1])
            set_run_default(r, italic=True)
        else:
            r = p.add_run(part)
            set_run_default(r, italic=italic)
    return p


